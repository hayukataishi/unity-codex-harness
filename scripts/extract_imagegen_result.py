#!/usr/bin/env python3
"""Extract a built-in image_gen PNG result from a Codex session JSONL file."""

from __future__ import annotations

import argparse
import base64
import binascii
import json
import re
import sys
from pathlib import Path
from typing import Any, Iterable


PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
IMAGE_EVENT_TYPE = "image_generation_end"
CALL_ID_KEYS = ("call_id", "callId", "tool_call_id", "toolCallId", "id")
PREFERRED_IMAGE_KEYS = (
    "result",
    "image",
    "image_base64",
    "imageBase64",
    "b64_json",
    "base64",
    "data",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Recover a PNG generated by the built-in image_gen tool from a "
            "Codex session JSONL transcript."
        )
    )
    parser.add_argument(
        "--session-jsonl",
        required=True,
        type=Path,
        help="Path to the Codex session JSONL transcript.",
    )
    parser.add_argument(
        "--call-id",
        required=True,
        help="image_gen tool call id to extract.",
    )
    parser.add_argument(
        "--output",
        required=True,
        type=Path,
        help="Destination PNG path.",
    )
    parser.add_argument(
        "--allow-overwrite",
        action="store_true",
        help="Replace the output file if it already exists.",
    )
    return parser.parse_args()


def event_payload(record: dict[str, Any]) -> dict[str, Any] | None:
    payload = record.get("payload")
    if isinstance(payload, dict):
        return payload
    if record.get("type") == IMAGE_EVENT_TYPE:
        return record
    return None


def call_id_matches(payload: dict[str, Any], expected: str) -> bool:
    for key in CALL_ID_KEYS:
        if payload.get(key) == expected:
            return True
    return False


def preferred_strings(value: Any) -> Iterable[str]:
    if isinstance(value, dict):
        for key in PREFERRED_IMAGE_KEYS:
            item = value.get(key)
            if isinstance(item, str):
                yield item
            elif item is not None:
                yield from preferred_strings(item)
        for key, item in value.items():
            if key not in PREFERRED_IMAGE_KEYS:
                yield from preferred_strings(item)
    elif isinstance(value, list):
        for item in value:
            yield from preferred_strings(item)
    elif isinstance(value, str):
        yield value


def normalize_base64(value: str) -> str:
    if value.startswith("data:image/png;base64,"):
        value = value.split(",", 1)[1]
    value = re.sub(r"\s+", "", value)
    padding = (-len(value)) % 4
    if padding:
        value = f"{value}{'=' * padding}"
    return value


def decode_png(value: str) -> bytes | None:
    try:
        decoded = base64.b64decode(normalize_base64(value), validate=True)
    except (binascii.Error, ValueError):
        return None
    if not decoded.startswith(PNG_SIGNATURE):
        return None
    return decoded


def png_size(data: bytes) -> tuple[int, int] | None:
    if len(data) < 24 or data[12:16] != b"IHDR":
        return None
    return (
        int.from_bytes(data[16:20], "big"),
        int.from_bytes(data[20:24], "big"),
    )


def extract_png(session_jsonl: Path, call_id: str) -> bytes:
    matched_event = False
    for line_number, line in enumerate(
        session_jsonl.read_text(encoding="utf-8").splitlines(),
        start=1,
    ):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as error:
            raise ValueError(
                f"{session_jsonl}:{line_number}: invalid JSON: {error}"
            ) from error
        if not isinstance(record, dict):
            continue
        payload = event_payload(record)
        if (
            payload is None
            or payload.get("type") != IMAGE_EVENT_TYPE
            or not call_id_matches(payload, call_id)
        ):
            continue
        matched_event = True
        for value in preferred_strings(payload):
            decoded = decode_png(value)
            if decoded is not None:
                return decoded
    if matched_event:
        raise ValueError(
            f"image_generation_end event for call id {call_id!r} "
            "did not contain a PNG base64 payload"
        )
    raise ValueError(
        f"no image_generation_end event found for call id {call_id!r}"
    )


def main() -> int:
    args = parse_args()
    if not args.session_jsonl.is_file():
        print(f"session JSONL not found: {args.session_jsonl}", file=sys.stderr)
        return 1
    if args.output.exists() and not args.allow_overwrite:
        print(
            f"output already exists, pass --allow-overwrite to replace it: "
            f"{args.output}",
            file=sys.stderr,
        )
        return 1
    try:
        png = extract_png(args.session_jsonl, args.call_id)
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    size = png_size(png)
    if size is None:
        print("decoded PNG is missing a valid IHDR chunk", file=sys.stderr)
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(png)
    width, height = size
    print(f"wrote {args.output} ({width}x{height}, {len(png)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
